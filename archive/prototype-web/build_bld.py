#!/usr/bin/env python3
"""Add real SF building footprints + heights to the Func map data.
Buildings are bucketed by height so the whole city renders as a handful of
paths, and each bucket's roof can be offset to extrude it as you zoom in."""
import json, math, os

SD = os.path.dirname(os.path.abspath(__file__))
base = json.load(open(os.path.join(SD, 'sfmap.json')))
LON0, LAT0, LON1, LAT1 = base['bbox']
W = base['w']


def mx(lon): return (lon + 180.0) / 360.0
def my(lat):
    s = math.sin(math.radians(lat))
    return 0.5 - math.log((1 + s) / (1 - s)) / (4 * math.pi)


X0, Y0 = mx(LON0), my(LAT1)
SC = W / (mx(LON1) - mx(LON0))
def proj(lon, lat): return ((mx(lon) - X0) * SC, (my(lat) - Y0) * SC)


def fmt(v):
    # 1 map unit ~= 1.25m, so whole units are plenty for a building corner
    return str(int(round(v)))


def poly(pts):
    return ("M%s,%s" % (fmt(pts[0][0]), fmt(pts[0][1]))
            + "".join("L%s,%s" % (fmt(x), fmt(y)) for x, y in pts[1:]) + "Z")


def height_of(tags):
    h = tags.get('height')
    if h:
        try: return float(str(h).replace('m', '').strip())
        except Exception: pass
    lv = tags.get('building:levels')
    if lv:
        try: return float(str(lv).split(';')[0]) * 3.2
        except Exception: pass
    return 8.0   # a plain low building


els = json.load(open(os.path.join(SD, 'sf_bld.json')))['elements']

# height buckets (metres) -> one path each
BUCKETS = [(0, 12), (12, 24), (24, 45), (45, 90), (90, 10000)]
paths = [[] for _ in BUCKETS]
kept = 0

for el in els:
    if el.get('type') != 'way' or 'geometry' not in el:
        continue
    g = el['geometry']
    if len(g) < 4:
        continue
    pts = [proj(p['lon'], p['lat']) for p in g]
    # drop anything fully outside the render window
    if not any(-200 <= x <= W + 200 and -200 <= y <= base['h'] + 200 for x, y in pts):
        continue
    # area cull — tiny sheds add weight and no visual value
    a = abs(sum(pts[i][0] * pts[(i + 1) % len(pts)][1]
                - pts[(i + 1) % len(pts)][0] * pts[i][1]
                for i in range(len(pts)))) / 2
    hgt = height_of(el.get('tags', {}))
    # small low buildings are texture, not landmarks — cull the tiniest hard
    if a < (150 if hgt < 12 else 45):
        continue
    # collapse near-collinear corners
    simp = [pts[0]]
    for i in range(1, len(pts)):
        if math.dist(pts[i], simp[-1]) >= 2.0:
            simp.append(pts[i])
    if len(simp) < 4:
        continue
    pts = simp
    for i, (lo, hi) in enumerate(BUCKETS):
        if lo <= hgt < hi:
            paths[i].append(poly(pts))
            kept += 1
            break

base['bld'] = [{'h': round((lo + min(hi, 140)) / 2, 1), 'd': ' '.join(p)}
               for (lo, hi), p in zip(BUCKETS, paths) if p]
base['bldMeta'] = {'count': kept}

out = ('// Real San Francisco geometry, from OpenStreetMap (ODbL).\n'
       '// Generated by build_map.py + build_bld.py — do not hand-edit.\n'
       'window.SFMAP=' + json.dumps(base, separators=(',', ':')) + ';\n')
p = ('/Users/phoenixbarnes/Library/Mobile Documents/com~apple~CloudDocs/'
     'All Files/Func/prototype-web/data/sfmap.js')
open(p, 'w').write(out)
json.dump(base, open(os.path.join(SD, 'sfmap.json'), 'w'), separators=(',', ':'))

print('buildings kept:', kept)
for b in base['bld']:
    print('  h=%-6s %8d chars' % (b['h'], len(b['d'])))
print('total file:', len(out), 'bytes')
